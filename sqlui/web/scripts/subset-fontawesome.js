// Generates a Font Awesome subset containing only the icons this UI uses.
//
// The templates keep using `<i class="fa fa-xxx">`; this script subsets
// fontawesome-webfont.ttf down to the used glyphs and emits small woff2/woff/ttf
// files plus a minimal CSS (base `.fa` + the used `.fa-xxx:before` rules).
// Keeping the font (rather than iconify/SVG) preserves `currentColor` and works
// in IE11.
//
// Regenerate after adding/removing an icon:
//   cd redisui/web && npm run subset-icons
const fs = require('fs');
const path = require('path');
const subsetFont = require('subset-font');

const ROOT = path.resolve(__dirname, '..');
const FA_DIR = path.join(ROOT, 'node_modules/font-awesome');
const OUT_FONTS = path.join(ROOT, 'src/assets/fonts');
const OUT_CSS = path.join(ROOT, 'src/assets/fontawesome-subset.css');

// Icons used by the UI (from `fa fa-*` usages + dynamic `fa-*-o` bindings).
const ICONS = [
  'fa-check',
  'fa-chevron-down',
  'fa-chevron-right',
  'fa-columns',
  'fa-database',
  'fa-download',
  'fa-exclamation-triangle',
  'fa-file-text-o',
  'fa-folder',
  'fa-folder-open',
  'fa-info-circle',
  'fa-list',
  'fa-pencil',
  'fa-play',
  'fa-plus',
  'fa-refresh',
  'fa-search',
  'fa-server',
  'fa-spinner',
  'fa-table',
  'fa-terminal',
  'fa-times',
  'fa-trash',
  'fa-upload',
];

function loadCodepoints() {
  const css = fs.readFileSync(path.join(FA_DIR, 'css/font-awesome.css'), 'utf8');
  const re = /\.(fa-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-fA-F]+)"/g;
  const map = {};
  let m;
  while ((m = re.exec(css)) !== null) {
    map[m[1]] = parseInt(m[2], 16);
  }
  return map;
}

(async () => {
  const contentByClass = loadCodepoints();
  const missing = ICONS.filter((c) => contentByClass[c] == null);
  if (missing.length) {
    console.error('No codepoint found for:', missing.join(', '));
    process.exit(1);
  }

  const text = String.fromCodePoint(...ICONS.map((c) => contentByClass[c]));
  const ttf = fs.readFileSync(path.join(FA_DIR, 'fonts/fontawesome-webfont.ttf'));

  fs.mkdirSync(OUT_FONTS, { recursive: true });
  const woff2 = await subsetFont(ttf, text, { targetFormat: 'woff2' });
  const woff = await subsetFont(ttf, text, { targetFormat: 'woff' });
  const subsetTtf = await subsetFont(ttf, text, { targetFormat: 'truetype' });

  fs.writeFileSync(path.join(OUT_FONTS, 'fontawesome-subset.woff2'), woff2);
  fs.writeFileSync(path.join(OUT_FONTS, 'fontawesome-subset.woff'), woff);
  fs.writeFileSync(path.join(OUT_FONTS, 'fontawesome-subset.ttf'), subsetTtf);

  const rules = ICONS.map((c) => {
    const hex = contentByClass[c].toString(16);
    return `.${c}:before { content: "\\${hex}"; }`;
  }).join('\n');

  const css = `/* Generated by scripts/subset-fontawesome.js — do not edit by hand. */
@font-face {
  font-family: 'FontAwesome';
  src: url('./fonts/fontawesome-subset.woff2') format('woff2'),
       url('./fonts/fontawesome-subset.woff') format('woff'),
       url('./fonts/fontawesome-subset.ttf') format('truetype');
  font-weight: normal;
  font-style: normal;
}
.fa {
  display: inline-block;
  font: normal normal normal 14px/1 FontAwesome;
  font-size: inherit;
  text-rendering: auto;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
${rules}
`;
  fs.writeFileSync(OUT_CSS, css);

  console.log(`subset ${ICONS.length} icons`);
  console.log('  woff2:', woff2.length, 'bytes');
  console.log('  woff :', woff.length, 'bytes');
  console.log('  ttf  :', subsetTtf.length, 'bytes');
  console.log('  css  :', css.length, 'bytes');
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
